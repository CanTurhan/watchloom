#!/usr/bin/env python3
"""Bundle CocoaPods' license notices without modifying the license text."""

import json
import plistlib
from pathlib import Path

project = Path(__file__).resolve().parents[1]
source = project / 'ios/Pods/Target Support Files/Pods-Runner/Pods-Runner-acknowledgements.plist'
with source.open('rb') as stream:
    acknowledgements = plistlib.load(stream)
records = [
    {'name': item['Title'], 'text': item['FooterText']}
    for item in acknowledgements['PreferenceSpecifiers']
    if item.get('Title') and item.get('FooterText') and item['Title'] != 'Acknowledgements'
]
if not records:
    raise ValueError('No native license notices were generated by CocoaPods.')
destination = project / 'assets/legal/ios_licenses.json'
destination.parent.mkdir(parents=True, exist_ok=True)
destination.write_text(json.dumps(records, ensure_ascii=False, indent=2) + '\n')
print(f'{len(records)} native license notices bundled in {destination.relative_to(project)}')
