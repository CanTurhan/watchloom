#!/usr/bin/env python3
"""Install the *public client configuration* of the Watchloom Firebase iOS app.

Never accepts service account JSON, private keys, passwords or OAuth tokens.
Validate all inputs before touching the project. Safe to run repeatedly.
"""
import argparse
import json
from pathlib import Path
import plistlib
import re

ROOT = Path(__file__).resolve().parents[1]
BUNDLE = "com.canturhan.watchloom"


def validate(config):
    if config.get("BUNDLE_ID") != BUNDLE:
        raise ValueError(f"Expected BUNDLE_ID {BUNDLE}; wrong iOS application.")
    for key in ("PROJECT_ID", "GOOGLE_APP_ID", "API_KEY", "GCM_SENDER_ID",
                "CLIENT_ID", "REVERSED_CLIENT_ID"):
        if not isinstance(config.get(key), str) or not config[key].strip():
            raise ValueError(f"Missing {key}. Enable Google Sign-In and download the iOS config again.")
    if not re.fullmatch(r"[a-z][a-z0-9-]{4,28}[a-z0-9]", config["PROJECT_ID"]):
        raise ValueError("Invalid Firebase project ID.")
    if not config["GOOGLE_APP_ID"].startswith(f"1:{config['GCM_SENDER_ID']}:ios:"):
        raise ValueError("GOOGLE_APP_ID and GCM_SENDER_ID do not match.")
    if not config["CLIENT_ID"].endswith(".apps.googleusercontent.com"):
        raise ValueError("Invalid iOS Google OAuth client ID.")
    if config["REVERSED_CLIENT_ID"] != ".".join(reversed(config["CLIENT_ID"].split("."))):
        raise ValueError("Google OAuth URL scheme does not match CLIENT_ID.")


def dart_string(value):
    return json.dumps(value).replace("$", r"\$")


def configure(config):
    validate(config)
    project_path = ROOT / 'ios/Runner.xcodeproj/project.pbxproj'
    project = project_path.read_text()
    build_id, ref_id = 'A0C140CC48DD43235EFA0001', 'A0C140CC48DD43235EFA0002'
    if 'GoogleService-Info.plist in Resources' not in project:
        replacements = {
            '/* End PBXBuildFile section */': f'\t\t{build_id} /* GoogleService-Info.plist in Resources */ = {{isa = PBXBuildFile; fileRef = {ref_id} /* GoogleService-Info.plist */; }};\n/* End PBXBuildFile section */',
            '/* End PBXFileReference section */': f'\t\t{ref_id} /* GoogleService-Info.plist */ = {{isa = PBXFileReference; lastKnownFileType = text.plist.xml; path = "GoogleService-Info.plist"; sourceTree = "<group>"; }};\n/* End PBXFileReference section */',
            '\t\t\t\t732BE3C94D790DA64A93D999 /* PrivacyInfo.xcprivacy */,': f'\t\t\t\t732BE3C94D790DA64A93D999 /* PrivacyInfo.xcprivacy */,\n\t\t\t\t{ref_id} /* GoogleService-Info.plist */,',
            '\t\t\t\tC06C4C07F0ED7F4016DCC58D /* PrivacyInfo.xcprivacy in Resources */,': f'\t\t\t\tC06C4C07F0ED7F4016DCC58D /* PrivacyInfo.xcprivacy in Resources */,\n\t\t\t\t{build_id} /* GoogleService-Info.plist in Resources */,',
        }
        for old, new in replacements.items():
            if project.count(old) != 1:
                raise ValueError('Xcode resource structure changed. Inspect before configuring Firebase.')
            project = project.replace(old, new)
    options = {
        "apiKey": config["API_KEY"], "appId": config["GOOGLE_APP_ID"],
        "messagingSenderId": config["GCM_SENDER_ID"], "projectId": config["PROJECT_ID"],
        "iosBundleId": BUNDLE, "iosClientId": config["CLIENT_ID"],
    }
    if config.get("STORAGE_BUCKET"):
        options["storageBucket"] = config["STORAGE_BUCKET"]
    source = "import 'package:firebase_core/firebase_core.dart';\n\n"
    source += "// Public Firebase client configuration; generated by configure_firebase_ios.py.\n"
    source += "abstract final class WatchloomFirebaseOptions {\n  static FirebaseOptions? get ios => const FirebaseOptions(\n"
    source += "".join(f"    {key}: {dart_string(value)},\n" for key, value in options.items())
    source += "  );\n}\n"

    info_path = ROOT / "ios/Runner/Info.plist"
    info = plistlib.loads(info_path.read_bytes())
    info["GIDClientID"] = config["CLIENT_ID"]
    url_types = [entry for entry in info.get("CFBundleURLTypes", [])
                 if entry.get("CFBundleURLName") != "watchloom.firebase.google"]
    url_types.append({"CFBundleURLName": "watchloom.firebase.google", "CFBundleTypeRole": "Editor",
                      "CFBundleURLSchemes": [config["REVERSED_CLIENT_ID"]]})
    info["CFBundleURLTypes"] = url_types
    info["FirebaseAnalyticsCollectionEnabled"] = False
    info["FIREBASE_ANALYTICS_COLLECTION_DEACTIVATED"] = True
    (ROOT / "lib/firebase_options.dart").write_text(source)
    native = dict(config, IS_ANALYTICS_ENABLED=False, IS_ADS_ENABLED=False)
    (ROOT / "ios/Runner/GoogleService-Info.plist").write_bytes(plistlib.dumps(native, sort_keys=False))
    info_path.write_bytes(plistlib.dumps(info, sort_keys=False))
    (ROOT / ".firebaserc").write_text(json.dumps({"projects": {"default": config["PROJECT_ID"]}}, indent=2) + "\n")
    project_path.write_text(project)
    print(f"Watchloom iOS configured for project: {config['PROJECT_ID']}")
    print("Next: enable the auth providers, deploy rules/functions, and test all three login methods on a device.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("plist", type=Path)
    args = parser.parse_args()
    try:
        configure(plistlib.loads(args.plist.expanduser().read_bytes()))
    except (ValueError, plistlib.InvalidFileException) as error:
        parser.exit(1, f"Configuration rejected: {error}\n")
